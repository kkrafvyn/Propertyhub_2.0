function deepMerge(base, patch) {
  const out = { ...base }
  for (const [k, v] of Object.entries(patch)) {
    if (v && typeof v === 'object' && !Array.isArray(v)) {
      out[k] = deepMerge(base[k] ?? {}, v)
    } else {
      out[k] = v
    }
  }
  return out
}

export function applyExtended(partial, code) {
  const ext = EXTENDED_BY_CODE[code]
  if (!ext) return partial
  return deepMerge(partial, ext)
}
