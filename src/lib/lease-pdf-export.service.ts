import type { GeneratedLeaseSchedule } from "./lease-clause-generator.service";

function escapeHtml(text: string): string {
  return text
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

function markdownToHtml(markdown: string): string {
  const lines = markdown.split("\n");
  const parts: string[] = [];
  let inList = false;

  for (const raw of lines) {
    const line = raw.trimEnd();
    if (line.startsWith("## ")) {
      if (inList) {
        parts.push("</ul>");
        inList = false;
      }
      parts.push(`<h2>${escapeHtml(line.slice(3))}</h2>`);
      continue;
    }
    if (line.startsWith("# ")) {
      if (inList) {
        parts.push("</ul>");
        inList = false;
      }
      parts.push(`<h1>${escapeHtml(line.slice(2))}</h1>`);
      continue;
    }
    if (line.startsWith("- ")) {
      if (!inList) {
        parts.push("<ul>");
        inList = true;
      }
      parts.push(`<li>${escapeHtml(line.slice(2)).replace(/\*\*(.*?)\*\*/g, "<strong>$1</strong>")}</li>`);
      continue;
    }
    if (line.startsWith("---")) {
      if (inList) {
        parts.push("</ul>");
        inList = false;
      }
      parts.push("<hr />");
      continue;
    }
    if (!line) {
      if (inList) {
        parts.push("</ul>");
        inList = false;
      }
      parts.push("<br />");
      continue;
    }
    if (inList) {
      parts.push("</ul>");
      inList = false;
    }
    parts.push(
      `<p>${escapeHtml(line).replace(/\*\*(.*?)\*\*/g, "<strong>$1</strong>")}</p>`
    );
  }

  if (inList) parts.push("</ul>");
  return parts.join("\n");
}

function buildPrintDocumentHtml(title: string, bodyHtml: string): string {
  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="utf-8" />
  <title>${escapeHtml(title)}</title>
  <style>
    body { font-family: Georgia, "Times New Roman", serif; max-width: 720px; margin: 2rem auto; padding: 0 1.5rem; color: #111; line-height: 1.55; font-size: 12pt; }
    h1 { font-size: 1.35rem; border-bottom: 2px solid #1a4d2e; padding-bottom: 0.35rem; }
    h2 { font-size: 1.05rem; margin-top: 1.25rem; color: #1a4d2e; }
    ul { padding-left: 1.25rem; }
    hr { border: none; border-top: 1px solid #ccc; margin: 1.5rem 0; }
    footer { margin-top: 2rem; font-size: 9pt; color: #666; }
    @media print { body { margin: 0; } }
  </style>
</head>
<body>
  ${bodyHtml}
  <footer>Generated by BaytMiftah — review with qualified local counsel before execution.</footer>
</body>
</html>`;
}

export function downloadLeaseScheduleHtml(
  schedule: GeneratedLeaseSchedule,
  filename = "lease-schedule.html"
) {
  if (typeof window === "undefined") return;
  const title = schedule.addendumTitle || `Lease — ${schedule.jurisdictionLabel}`;
  const html = buildPrintDocumentHtml(title, markdownToHtml(schedule.markdown));
  const blob = new Blob([html], { type: "text/html;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = filename;
  link.click();
  URL.revokeObjectURL(url);
}

/** Opens browser print dialog — user can save as PDF without extra dependencies. */
export function printLeaseScheduleAsPdf(
  schedule: GeneratedLeaseSchedule,
  title?: string
) {
  if (typeof window === "undefined") return;
  const docTitle = title || schedule.addendumTitle || `Lease — ${schedule.jurisdictionLabel}`;
  const html = buildPrintDocumentHtml(docTitle, markdownToHtml(schedule.markdown));
  const printWindow = window.open("", "_blank", "noopener,noreferrer,width=900,height=700");
  if (!printWindow) return;
  printWindow.document.write(html);
  printWindow.document.close();
  printWindow.focus();
  printWindow.print();
}

export const leasePdfExportService = {
  markdownToHtml,
  downloadLeaseScheduleHtml,
  printLeaseScheduleAsPdf,
};
